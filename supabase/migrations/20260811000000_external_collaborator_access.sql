-- Full-access users may legitimately produce repeated task events, but an
-- outbound transport must not become an unbounded relay to a related-only
-- recipient. The service role atomically claims one delivery per rolling minute
-- for the exact recipient/task/context/type/channel tuple. A NULL claim means a
-- delivery was claimed in the preceding 60 seconds. Failed deliveries may retry
-- after that interval; successful delivery is recorded by the opaque claim ID.
CREATE OR REPLACE FUNCTION public.claim_restricted_task_notification_delivery(
  p_recipient_id uuid,
  p_task_id uuid,
  p_context_team_id uuid,
  p_notification_type text,
  p_channel text
)
RETURNS uuid
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
DECLARE
  v_claim_id uuid;
  v_now timestamptz := clock_timestamp();
  v_window_started_at timestamptz := date_trunc('minute', v_now);
BEGIN
  IF COALESCE(auth.jwt() ->> 'role', '') <> 'service_role' THEN
    RAISE EXCEPTION 'Service role required';
  END IF;
  IF p_notification_type IS NULL OR NOT (
    p_notification_type = ANY (ARRAY[
      'task_assigned', 'task_status_changed', 'task_updated',
      'task_deadline_reminder'
    ]::text[])
  ) THEN
    RAISE EXCEPTION 'Invalid restricted task notification type';
  END IF;
  IF p_channel IS NULL OR NOT (p_channel = ANY (ARRAY['email', 'telegram']::text[])) THEN
    RAISE EXCEPTION 'Invalid notification channel';
  END IF;
  IF NOT EXISTS (
    SELECT 1
    FROM public.profiles recipient
    JOIN public.task_access_grants grant_row
      ON grant_row.profile_id = recipient.id
     AND grant_row.task_id = p_task_id
     AND grant_row.context_team_id = p_context_team_id
    JOIN public.tasks task_row
      ON task_row.id = grant_row.task_id
     AND task_row.deleted_at IS NULL
    WHERE recipient.id = p_recipient_id
      AND recipient.access_scope = 'related_only'
  ) THEN
    RAISE EXCEPTION 'Restricted recipient has no live task context access';
  END IF;

  -- Serialize only this delivery tuple. Hash collisions can at worst serialize
  -- unrelated claims; they cannot authorize or suppress a committed claim.
  PERFORM pg_advisory_xact_lock(
    hashtextextended(
      concat_ws(
        '|',
        p_recipient_id::text,
        p_task_id::text,
        p_context_team_id::text,
        p_notification_type,
        p_channel
      ),
      0
    )
  );

  IF EXISTS (
    SELECT 1
    FROM public.restricted_task_notification_deliveries delivery
    WHERE delivery.recipient_id = p_recipient_id
      AND delivery.task_id = p_task_id
      AND delivery.context_team_id = p_context_team_id
      AND delivery.notification_type = p_notification_type
      AND delivery.channel = p_channel
      AND delivery.claimed_at > v_now - interval '60 seconds'
  ) THEN
    RETURN NULL;
  END IF;

  INSERT INTO public.restricted_task_notification_deliveries(
    recipient_id,
    task_id,
    context_team_id,
    notification_type,
    channel,
    window_started_at
  ) VALUES (
    p_recipient_id,
    p_task_id,
    p_context_team_id,
    p_notification_type,
    p_channel,
    v_window_started_at
  )
  ON CONFLICT DO NOTHING
  RETURNING claim_id INTO v_claim_id;

  RETURN v_claim_id;
END;
$$;

