CREATE OR REPLACE FUNCTION public.rebuild_grants_for_task_row()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
BEGIN
  PERFORM public.rebuild_task_access_grants(COALESCE(NEW.id, OLD.id));
  RETURN COALESCE(NEW, OLD);
