  IF NOT FOUND THEN
    RAISE EXCEPTION 'Profile not found';
  END IF;
  RETURN v_profile;
END;
$$;

CREATE OR REPLACE FUNCTION public.set_member_access_scope(
  p_profile_id uuid,
  p_access_scope text,
  p_team_ids uuid[] DEFAULT '{}'::uuid[],
  p_role text DEFAULT 'user'
)
RETURNS SETOF public.profiles
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
DECLARE
  v_primary_team_id uuid;
  v_expected_count integer;
  v_existing_count integer;
  v_profile public.profiles%ROWTYPE;
BEGIN
  IF NOT public.is_admin() OR NOT public.is_full_access() THEN
    RAISE EXCEPTION 'Only full-access admins can change member access';
  END IF;
  IF p_access_scope NOT IN ('full', 'related_only') THEN
    RAISE EXCEPTION 'Invalid access scope';
  END IF;
  IF p_role NOT IN ('admin', 'editor', 'user') THEN
    RAISE EXCEPTION 'Invalid role';
  END IF;
  IF NOT EXISTS (SELECT 1 FROM public.profiles WHERE id = p_profile_id) THEN
    RAISE EXCEPTION 'Profile not found';
  END IF;
  IF EXISTS (
       SELECT 1 FROM public.profiles
       WHERE id = p_profile_id AND access_scope = 'full' AND role = 'admin'
     )
     AND (p_access_scope <> 'full' OR p_role <> 'admin')
     AND NOT EXISTS (
       SELECT 1 FROM public.profiles
       WHERE id <> p_profile_id AND access_scope = 'full' AND role = 'admin'
     ) THEN
    RAISE EXCEPTION 'The last full-access admin cannot be demoted';
  END IF;

  IF p_access_scope = 'related_only' THEN
    IF p_role <> 'user' OR cardinality(COALESCE(p_team_ids, '{}'::uuid[])) <> 0 THEN
      RAISE EXCEPTION 'External collaborators must use role user and have no teams';
    END IF;
    UPDATE public.profiles
    SET access_scope = 'related_only', role = 'user', team_id = NULL
    WHERE id = p_profile_id
    RETURNING * INTO v_profile;

    -- Keep the conversion self-contained even if this RPC is reused without
    -- the defensive profile trigger in a future schema revision.
    DELETE FROM public.team_members WHERE profile_id = p_profile_id;
  ELSE
    IF cardinality(COALESCE(p_team_ids, '{}'::uuid[])) = 0 THEN
      RAISE EXCEPTION 'At least one team is required for full access';
    END IF;
    IF cardinality(p_team_ids) <> cardinality(ARRAY(SELECT DISTINCT unnest(p_team_ids))) THEN
      RAISE EXCEPTION 'Duplicate team IDs are not allowed';
    END IF;

    SELECT count(*) INTO v_existing_count
    FROM public.teams WHERE id = ANY(p_team_ids);
    v_expected_count := cardinality(p_team_ids);
    IF v_existing_count <> v_expected_count THEN
      RAISE EXCEPTION 'One or more teams do not exist';
    END IF;

    v_primary_team_id := p_team_ids[1];
    UPDATE public.profiles
    SET access_scope = 'full', role = p_role, team_id = v_primary_team_id
    WHERE id = p_profile_id
    RETURNING * INTO v_profile;

    UPDATE public.team_members
    SET is_primary = false
    WHERE profile_id = p_profile_id AND is_primary;

    DELETE FROM public.team_members
    WHERE profile_id = p_profile_id
      AND NOT (team_id = ANY(p_team_ids));

    INSERT INTO public.team_members(team_id, profile_id, is_primary, sort_order)
    SELECT team_id, p_profile_id, false, ordinality - 1
    FROM unnest(p_team_ids) WITH ORDINALITY AS requested(team_id, ordinality)
    ON CONFLICT (team_id, profile_id) DO UPDATE
    SET sort_order = EXCLUDED.sort_order;

    UPDATE public.team_members
    SET is_primary = true
    WHERE profile_id = p_profile_id AND team_id = v_primary_team_id;
  END IF;

  RETURN NEXT v_profile;
END;
$$;

-- Service-role-only companion for the invite Edge Function. The auth trigger may
-- already have inserted the profile, so this is deliberately an upsert.
CREATE OR REPLACE FUNCTION public.finalize_invited_profile(
  p_auth_user_id uuid,
  p_name text,
  p_role text,
  p_job_title text,
  p_avatar text,
  p_team_id uuid,
  p_access_scope text
)
RETURNS SETOF public.profiles
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
DECLARE
  v_profile public.profiles%ROWTYPE;
BEGIN
  IF COALESCE(auth.jwt() ->> 'role', '') <> 'service_role' THEN
    RAISE EXCEPTION 'Service role required';
  END IF;
  IF p_access_scope NOT IN ('full', 'related_only') THEN
    RAISE EXCEPTION 'Invalid access scope';
  END IF;
  IF p_role NOT IN ('admin', 'editor', 'user') THEN
    RAISE EXCEPTION 'Invalid role';
  END IF;
  IF p_access_scope = 'related_only' AND (p_role <> 'user' OR p_team_id IS NOT NULL) THEN
    RAISE EXCEPTION 'External collaborators must use role user and have no team';
  END IF;
  IF p_access_scope = 'full' AND p_team_id IS NULL THEN
    RAISE EXCEPTION 'A team is required for full-access invitations';
  END IF;
  IF p_team_id IS NOT NULL AND NOT EXISTS (SELECT 1 FROM public.teams WHERE id = p_team_id) THEN
    RAISE EXCEPTION 'Team not found';
  END IF;

  INSERT INTO public.profiles(
    auth_user_id, name, role, job_title, avatar, team_id, status, access_scope
