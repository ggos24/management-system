$$;

CREATE OR REPLACE FUNCTION public.get_visible_profile_summaries()
RETURNS TABLE(id uuid, name text, avatar text)
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
  WITH my_contexts AS (
    SELECT DISTINCT g.task_id, g.context_team_id
    FROM public.task_access_grants g
    JOIN public.tasks t ON t.id = g.task_id AND t.deleted_at IS NULL
    WHERE g.profile_id = public.current_profile_id()
  ), my_tasks AS (
    SELECT DISTINCT mc.task_id FROM my_contexts mc
  ), visible_profile_ids AS (
    SELECT public.current_profile_id() AS profile_id
    UNION
    SELECT p.id
    FROM public.profiles p
    WHERE public.is_full_access()
    UNION
    SELECT g.profile_id
    FROM public.task_access_grants g
    JOIN my_contexts mc
      ON mc.task_id = g.task_id
     AND mc.context_team_id = g.context_team_id
    UNION
    SELECT g.profile_id
    FROM public.task_access_grants g
    JOIN public.tasks t
      ON t.id = g.task_id
     AND t.team_id = g.context_team_id
    JOIN my_tasks mt ON mt.task_id = g.task_id
    UNION
    SELECT c.user_id
    FROM public.task_comments c
    JOIN my_tasks mt ON mt.task_id = c.task_id
    UNION
    SELECT a.user_id
    FROM public.task_activity a
    JOIN my_tasks mt ON mt.task_id = a.task_id
    UNION
    SELECT m.profile_id
    FROM public.task_comment_mentions m
    JOIN my_tasks mt ON mt.task_id = m.task_id
  )
  SELECT p.id, p.name, p.avatar
  FROM public.profiles p
  JOIN visible_profile_ids visible ON visible.profile_id = p.id
  ORDER BY p.name, p.id
$$;

