-- Outbound transports need their own replay ledger; the in-app notification
-- unique index cannot prevent repeated email/Telegram Edge Function calls.
-- A claim is intentionally single-shot per channel. Failed sends remain
-- claimed for manual operator retry rather than enabling attacker-driven loops.
CREATE TABLE public.external_notification_deliveries (
  comment_id uuid NOT NULL REFERENCES public.task_comments(id) ON DELETE CASCADE,
  recipient_id uuid NOT NULL REFERENCES public.profiles(id) ON DELETE CASCADE,
  channel text NOT NULL CHECK (channel IN ('email', 'telegram')),
  claimed_at timestamptz NOT NULL DEFAULT now(),
  sent_at timestamptz,
  PRIMARY KEY (comment_id, recipient_id, channel)
);

-- Non-comment task transports allow legitimate repeated updates, so use a
-- short rolling window instead of the permanent comment-delivery key. Different
-- event types and channels remain independent within the same rolling window.
CREATE TABLE public.restricted_task_notification_deliveries (
  claim_id uuid NOT NULL DEFAULT gen_random_uuid() UNIQUE,
  recipient_id uuid NOT NULL REFERENCES public.profiles(id) ON DELETE CASCADE,
  task_id uuid NOT NULL REFERENCES public.tasks(id) ON DELETE CASCADE,
  context_team_id uuid NOT NULL REFERENCES public.teams(id) ON DELETE CASCADE,
  notification_type text NOT NULL CHECK (
    notification_type IN (
      'task_assigned', 'task_status_changed', 'task_updated',
      'task_deadline_reminder'
    )
  ),
  channel text NOT NULL CHECK (channel IN ('email', 'telegram')),
  window_started_at timestamptz NOT NULL,
  claimed_at timestamptz NOT NULL DEFAULT now(),
  sent_at timestamptz,
  PRIMARY KEY (
    recipient_id, task_id, context_team_id, notification_type,
    channel, window_started_at
  )
);

CREATE INDEX idx_restricted_task_notification_deliveries_claimed
  ON public.restricted_task_notification_deliveries(claimed_at);

-- Public sign-up is enabled in this project. A raw auth sign-up must therefore
-- land in the least-privileged scope; only the verified admin invite flow may
-- promote it through finalize_invited_profile().
CREATE OR REPLACE FUNCTION public.handle_new_user()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
DECLARE
  v_profile_id uuid;
BEGIN
  INSERT INTO public.profiles(
    auth_user_id, name, role, access_scope, team_id, job_title, avatar, status
  ) VALUES (
    NEW.id,
    COALESCE(
      NULLIF(NEW.raw_user_meta_data ->> 'name', ''),
      NULLIF(NEW.raw_user_meta_data ->> 'full_name', ''),
      NULLIF(split_part(COALESCE(NEW.email, ''), '@', 1), ''),
      'User'
    ),
    'user',
    'related_only',
    NULL,
    NULLIF(NEW.raw_user_meta_data ->> 'job_title', ''),
    COALESCE(
      NULLIF(NEW.raw_user_meta_data ->> 'avatar', ''),
      NULLIF(NEW.raw_user_meta_data ->> 'avatar_url', '')
    ),
    'active'
  )
  ON CONFLICT (auth_user_id) DO UPDATE
  SET name = EXCLUDED.name,
      role = 'user',
      access_scope = 'related_only',
      team_id = NULL,
      job_title = COALESCE(EXCLUDED.job_title, public.profiles.job_title),
      avatar = COALESCE(EXCLUDED.avatar, public.profiles.avatar)
  RETURNING id INTO v_profile_id;

  INSERT INTO public.permissions(member_id, can_create, can_edit, can_delete)
  VALUES (v_profile_id, true, false, false)
  ON CONFLICT (member_id) DO NOTHING;
  RETURN NEW;
END;
$$;

