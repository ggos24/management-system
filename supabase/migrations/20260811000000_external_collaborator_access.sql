-- task_comments.context_team_id intentionally preserves a comment independently
-- from a linked workspace, so its FK cannot cascade on team deletion. Remap
-- linked-context comments to the task's home workspace before team/link cascades
-- run. Mentions are copied with an OR merge before the old-context rows are
-- removed, preserving the strongest grants_access value without PK conflicts.
CREATE OR REPLACE FUNCTION public.remap_linked_comment_contexts_before_team_delete()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
BEGIN
  -- A concurrent task home-team move must not let the mention and comment
  -- statements observe different destinations. Lock in a stable order to also
  -- avoid deadlocks when one statement deletes multiple teams.
  PERFORM task_row.id
  FROM public.tasks task_row
  WHERE task_row.team_id <> OLD.id
    AND (
      EXISTS (
        SELECT 1
        FROM public.task_comments comment_row
        WHERE comment_row.task_id = task_row.id
          AND comment_row.context_team_id = OLD.id
      )
      OR EXISTS (
        SELECT 1
        FROM public.task_comment_mentions mention
        WHERE mention.task_id = task_row.id
          AND mention.context_team_id = OLD.id
      )
    )
  ORDER BY task_row.id
  FOR UPDATE;

  INSERT INTO public.task_comment_mentions(
    comment_id,
    task_id,
    profile_id,
    context_team_id,
    grants_access,
    created_at
  )
  SELECT mention.comment_id,
         mention.task_id,
         mention.profile_id,
         task_row.team_id,
         mention.grants_access,
         mention.created_at
  FROM public.task_comment_mentions mention
  JOIN public.tasks task_row ON task_row.id = mention.task_id
  WHERE mention.context_team_id = OLD.id
    AND task_row.team_id <> OLD.id
  ON CONFLICT (comment_id, profile_id, context_team_id) DO UPDATE
  SET grants_access = public.task_comment_mentions.grants_access OR EXCLUDED.grants_access,
      created_at = LEAST(public.task_comment_mentions.created_at, EXCLUDED.created_at);

  DELETE FROM public.task_comment_mentions mention
  USING public.tasks task_row
  WHERE mention.task_id = task_row.id
    AND mention.context_team_id = OLD.id
    AND task_row.team_id <> OLD.id;

  UPDATE public.task_comments comment_row
  SET context_team_id = task_row.team_id
  FROM public.tasks task_row
  WHERE comment_row.task_id = task_row.id
    AND comment_row.context_team_id = OLD.id
    AND task_row.team_id <> OLD.id;

  UPDATE public.notifications notification_row
  SET entity_data = notification_row.entity_data
    || CASE
         WHEN public.try_uuid(notification_row.entity_data ->> 'contextTeamId') = OLD.id
           THEN jsonb_build_object('contextTeamId', task_row.team_id::text)
         ELSE '{}'::jsonb
       END
    || CASE
         WHEN public.try_uuid(notification_row.entity_data ->> 'teamId') = OLD.id
           THEN jsonb_build_object('teamId', task_row.team_id::text)
         ELSE '{}'::jsonb
       END
  FROM public.tasks task_row
  WHERE task_row.team_id <> OLD.id
    AND public.try_uuid(notification_row.entity_data ->> 'taskId') = task_row.id
    AND notification_row.type IN (
      'task_assigned',
      'task_status_changed',
      'task_updated',
      'task_unassigned',
      'task_deleted',
      'task_deadline_reminder',
      'comment_mention'
    )
    AND (
      public.try_uuid(notification_row.entity_data ->> 'contextTeamId') = OLD.id
      OR public.try_uuid(notification_row.entity_data ->> 'teamId') = OLD.id
    );

  RETURN OLD;
END;
$$;

CREATE TRIGGER trg_teams_remap_linked_comment_contexts
BEFORE DELETE ON public.teams
FOR EACH ROW EXECUTE FUNCTION public.remap_linked_comment_contexts_before_team_delete();

