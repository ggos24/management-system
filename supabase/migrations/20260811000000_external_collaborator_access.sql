CREATE OR REPLACE FUNCTION public.update_own_profile(
  p_name text DEFAULT NULL,
  p_job_title text DEFAULT NULL,
  p_avatar text DEFAULT NULL
)
RETURNS public.profiles
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
