ALTER TABLE public.profiles
  DROP CONSTRAINT IF EXISTS profiles_related_only_shape_check;
ALTER TABLE public.profiles
  ADD CONSTRAINT profiles_related_only_shape_check
  CHECK (
    access_scope <> 'related_only'
    OR (role IS NOT DISTINCT FROM 'user' AND team_id IS NULL)
  );

