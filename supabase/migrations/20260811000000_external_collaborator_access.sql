CREATE OR REPLACE FUNCTION public.try_uuid(p_value text)
RETURNS uuid
LANGUAGE plpgsql
IMMUTABLE
AS $$
BEGIN
  IF p_value IS NULL OR p_value = '' THEN
    RETURN NULL;
  END IF;
  RETURN p_value::uuid;
EXCEPTION WHEN invalid_text_representation THEN
  RETURN NULL;
END;
$$;

CREATE OR REPLACE FUNCTION public.jsonb_profile_ids(p_value jsonb)
RETURNS SETOF uuid
LANGUAGE sql
IMMUTABLE
SET search_path = public, pg_temp
AS $$
  SELECT DISTINCT public.try_uuid(v.value)
  FROM (
    SELECT trim(both '"' from p_value::text) AS value
    WHERE jsonb_typeof(p_value) = 'string'
    UNION ALL
    SELECT jsonb_array_elements_text(p_value) AS value
    WHERE jsonb_typeof(p_value) = 'array'
  ) AS v
  WHERE public.try_uuid(v.value) IS NOT NULL
$$;

