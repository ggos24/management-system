CREATE OR REPLACE FUNCTION public.external_comment_notification_allowed(
  p_recipient_id uuid,
  p_entity_data jsonb
)
RETURNS boolean
LANGUAGE plpgsql
STABLE
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
DECLARE
  v_task_id uuid;
  v_context_team_id uuid;
  v_comment_id uuid;
BEGIN
  v_task_id := public.try_uuid(p_entity_data ->> 'taskId');
  v_context_team_id := public.try_uuid(
    COALESCE(p_entity_data ->> 'contextTeamId', p_entity_data ->> 'teamId')
  );
  v_comment_id := public.try_uuid(p_entity_data ->> 'commentId');
  IF v_task_id IS NULL OR v_context_team_id IS NULL OR v_comment_id IS NULL THEN
    RETURN false;
  END IF;
  RETURN public.has_related_context_access(v_task_id, v_context_team_id)
    AND EXISTS (
      SELECT 1
      FROM public.task_access_grants g
      WHERE g.task_id = v_task_id
        AND g.context_team_id = v_context_team_id
        AND g.profile_id = p_recipient_id
    )
    AND EXISTS (
      SELECT 1
      FROM public.task_comment_mentions m
      JOIN public.task_comments c ON c.id = m.comment_id
      WHERE m.comment_id = v_comment_id
        AND m.task_id = v_task_id
        AND m.context_team_id = v_context_team_id
        AND m.profile_id = p_recipient_id
        AND c.user_id = public.current_profile_id()
    )
    AND NOT EXISTS (
      SELECT 1
      FROM public.notification_preferences preference
      WHERE preference.user_id = p_recipient_id
        AND preference.category = 'mentions'
        AND preference.channel = 'in_app'
        AND preference.enabled = false
    );
END;
$$;

