-- Replace every public-table policy touched by this feature. Recreating the
-- matrix avoids an older permissive policy being OR'ed with a restrictive one.
DO $$
DECLARE
  policy_row record;
BEGIN
  FOR policy_row IN
    SELECT schemaname, tablename, policyname
    FROM pg_policies
    WHERE schemaname = 'public'
      AND tablename = ANY (ARRAY[
        'profiles', 'teams', 'tasks', 'task_assignees', 'placements',
        'task_placements', 'team_statuses', 'team_content_types',
        'custom_properties', 'absences', 'shifts', 'permissions',
        'activity_log', 'app_settings', 'notifications', 'telegram_links',
        'task_comments', 'docs', 'user_team_orders', 'task_team_links',
        'team_placements', 'task_activity', 'task_deadline_reminders',
        'notification_preferences', 'team_members', 'team_hidden_columns',
        'team_person_field_config', 'tickets', 'ticket_comments',
        'task_comment_mentions', 'task_access_grants',
        'task_access_revisions', 'external_access_migration_report',
        'external_notification_deliveries',
        'restricted_task_notification_deliveries'
      ])
  LOOP
    EXECUTE format(
      'DROP POLICY IF EXISTS %I ON %I.%I',
      policy_row.policyname,
      policy_row.schemaname,
      policy_row.tablename
    );
  END LOOP;
END;
$$;

