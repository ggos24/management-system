CREATE OR REPLACE FUNCTION public.save_task_with_relations(
  p_task jsonb,
  p_assignee_ids uuid[] DEFAULT '{}'::uuid[],
  p_placement_names text[] DEFAULT '{}'::text[]
)
RETURNS uuid
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
DECLARE
  v_task_id uuid;
  v_team_id uuid;
  v_invalid_count integer;
  v_can_mutate_placements boolean;
  v_existing_placement_names text[];
  v_requested_placement_names text[];
BEGIN
  IF NOT public.is_full_access() THEN
    RAISE EXCEPTION 'External collaborators cannot modify tasks';
  END IF;

  v_task_id := COALESCE(public.try_uuid(p_task ->> 'id'), gen_random_uuid());
  v_team_id := public.try_uuid(p_task ->> 'team_id');
  IF v_team_id IS NULL OR NOT EXISTS (SELECT 1 FROM public.teams WHERE id = v_team_id) THEN
    RAISE EXCEPTION 'A valid team_id is required';
  END IF;
  IF btrim(COALESCE(p_task ->> 'title', '')) = '' THEN
    RAISE EXCEPTION 'Task title is required';
  END IF;

  v_can_mutate_placements := public.is_editor() OR v_team_id = (
    SELECT ap.team_id FROM public.auth_profile() ap
  );
  SELECT COALESCE(array_agg(DISTINCT p.name ORDER BY p.name), '{}'::text[])
  INTO v_existing_placement_names
  FROM public.task_placements tp
  JOIN public.placements p ON p.id = tp.placement_id
  WHERE tp.task_id = v_task_id;
  SELECT COALESCE(array_agg(name ORDER BY name), '{}'::text[])
  INTO v_requested_placement_names
  FROM (
    SELECT DISTINCT requested.name
    FROM unnest(COALESCE(p_placement_names, '{}'::text[])) requested(name)
    WHERE requested.name <> ''
  ) normalized;
  IF NOT v_can_mutate_placements
     AND v_existing_placement_names IS DISTINCT FROM v_requested_placement_names THEN
    RAISE EXCEPTION 'You cannot change placements for a task outside your team';
  END IF;

  SELECT count(*) INTO v_invalid_count
  FROM (SELECT DISTINCT unnest(COALESCE(p_assignee_ids, '{}'::uuid[])) AS id) requested
  LEFT JOIN public.profiles p ON p.id = requested.id
  WHERE p.id IS NULL;
  IF v_invalid_count > 0 THEN
    RAISE EXCEPTION 'One or more assignees do not exist';
  END IF;

  IF NOT public.is_editor() AND EXISTS (
    SELECT 1
    FROM unnest(COALESCE(p_placement_names, '{}'::text[])) requested(name)
    LEFT JOIN public.placements p ON p.name = requested.name
    WHERE p.id IS NULL
  ) THEN
    RAISE EXCEPTION 'Only editors can create new placements';
  END IF;

  INSERT INTO public.tasks(
    id, title, description, team_id, status_id, priority, due_date, done_date,
    content_type, notes, editor_ids, designer_ids, links, files,
    custom_field_values, sort_order
  ) VALUES (
    v_task_id,
    p_task ->> 'title',
    COALESCE(p_task ->> 'description', ''),
    v_team_id,
    public.try_uuid(p_task ->> 'status_id'),
    COALESCE(NULLIF(p_task ->> 'priority', ''), 'medium'),
    NULLIF(p_task ->> 'due_date', '')::date,
    NULLIF(p_task ->> 'done_date', '')::date,
    NULLIF(p_task ->> 'content_type', ''),
    NULLIF(p_task ->> 'notes', ''),
    COALESCE(p_task -> 'editor_ids', '[]'::jsonb),
    COALESCE(p_task -> 'designer_ids', '[]'::jsonb),
    COALESCE(p_task -> 'links', '[]'::jsonb),
    COALESCE(p_task -> 'files', '[]'::jsonb),
    COALESCE(p_task -> 'custom_field_values', '{}'::jsonb),
    COALESCE((p_task ->> 'sort_order')::integer, 0)
  )
  ON CONFLICT (id) DO UPDATE
  SET title = EXCLUDED.title,
      description = EXCLUDED.description,
      team_id = EXCLUDED.team_id,
      status_id = EXCLUDED.status_id,
      priority = EXCLUDED.priority,
      due_date = EXCLUDED.due_date,
      done_date = EXCLUDED.done_date,
      content_type = EXCLUDED.content_type,
      notes = EXCLUDED.notes,
      editor_ids = EXCLUDED.editor_ids,
      designer_ids = EXCLUDED.designer_ids,
      links = EXCLUDED.links,
      files = EXCLUDED.files,
      custom_field_values = EXCLUDED.custom_field_values,
      sort_order = EXCLUDED.sort_order;

  DELETE FROM public.task_assignees a
  WHERE a.task_id = v_task_id
    AND NOT (a.member_id = ANY(COALESCE(p_assignee_ids, '{}'::uuid[])));

  INSERT INTO public.task_assignees(task_id, member_id, sort_order)
  SELECT v_task_id, requested.member_id, min(requested.ordinality)::integer - 1
  FROM unnest(COALESCE(p_assignee_ids, '{}'::uuid[])) WITH ORDINALITY
       AS requested(member_id, ordinality)
  GROUP BY requested.member_id
  ON CONFLICT (task_id, member_id) DO UPDATE
  SET sort_order = EXCLUDED.sort_order;

  IF v_can_mutate_placements THEN
    IF public.is_editor() THEN
      INSERT INTO public.placements(name)
      SELECT DISTINCT btrim(name)
      FROM unnest(COALESCE(p_placement_names, '{}'::text[])) requested(name)
      WHERE btrim(name) <> ''
      ON CONFLICT (name) DO NOTHING;
    END IF;

    DELETE FROM public.task_placements tp
    WHERE tp.task_id = v_task_id
      AND NOT EXISTS (
        SELECT 1
        FROM public.placements p
        WHERE p.id = tp.placement_id
          AND p.name = ANY(COALESCE(p_placement_names, '{}'::text[]))
      );

    INSERT INTO public.task_placements(task_id, placement_id)
    SELECT DISTINCT v_task_id, p.id
    FROM public.placements p
    WHERE p.name = ANY(COALESCE(p_placement_names, '{}'::text[]))
    ON CONFLICT DO NOTHING;
  END IF;

  PERFORM public.rebuild_task_access_grants(v_task_id);
  RETURN v_task_id;
END;
$$;

CREATE OR REPLACE FUNCTION public.resolve_task_context(
  p_task_id uuid,
  p_context_team_id uuid
)
RETURNS uuid
LANGUAGE plpgsql
STABLE
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
DECLARE
  v_home_team_id uuid;
  v_context_team_id uuid;
BEGIN
  SELECT t.team_id INTO v_home_team_id
  FROM public.tasks t
  WHERE t.id = p_task_id AND t.deleted_at IS NULL;
  IF v_home_team_id IS NULL THEN
    RAISE EXCEPTION 'Task unavailable';
  END IF;

  v_context_team_id := COALESCE(p_context_team_id, v_home_team_id);
  IF v_context_team_id <> v_home_team_id AND NOT EXISTS (
    SELECT 1 FROM public.task_team_links link
    WHERE link.task_id = p_task_id AND link.team_id = v_context_team_id
  ) THEN
    RAISE EXCEPTION 'Invalid task context';
  END IF;
  RETURN v_context_team_id;
END;
$$;

CREATE OR REPLACE FUNCTION public.validate_comment_mentions(
  p_task_id uuid,
  p_context_team_id uuid,
  p_mentioned_profile_ids uuid[]
)
RETURNS void
LANGUAGE plpgsql
STABLE
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
DECLARE
  v_expected_count integer;
  v_existing_count integer;
BEGIN
  v_expected_count := cardinality(ARRAY(
    SELECT DISTINCT unnest(COALESCE(p_mentioned_profile_ids, '{}'::uuid[]))
  ));
  SELECT count(*) INTO v_existing_count
  FROM public.profiles p
  WHERE p.id = ANY(COALESCE(p_mentioned_profile_ids, '{}'::uuid[]));
  IF v_existing_count <> v_expected_count THEN
    RAISE EXCEPTION 'One or more mentioned profiles do not exist';
  END IF;

  IF NOT public.is_full_access() AND EXISTS (
    SELECT 1
    FROM unnest(COALESCE(p_mentioned_profile_ids, '{}'::uuid[])) mentioned(profile_id)
    WHERE NOT EXISTS (
      SELECT 1
      FROM public.task_access_grants g
      WHERE g.task_id = p_task_id
        AND g.context_team_id = p_context_team_id
        AND g.profile_id = mentioned.profile_id
    )
  ) THEN
    RAISE EXCEPTION 'External collaborators may mention only existing task participants';
  END IF;
END;
$$;

CREATE OR REPLACE FUNCTION public.create_task_comment_with_mentions(
  p_task_id uuid,
  p_content text,
  p_context_team_id uuid DEFAULT NULL,
  p_mentioned_profile_ids uuid[] DEFAULT '{}'::uuid[]
)
RETURNS uuid
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
DECLARE
  v_profile_id uuid;
  v_context_team_id uuid;
  v_comment_id uuid;
  v_grants_access boolean;
BEGIN
  v_profile_id := public.current_profile_id();
  IF v_profile_id IS NULL THEN
    RAISE EXCEPTION 'Profile not found';
  END IF;
  IF btrim(COALESCE(p_content, '')) = '' THEN
    RAISE EXCEPTION 'Comment cannot be empty';
  END IF;
  IF NOT public.is_full_access() AND NOT public.has_related_task_access(p_task_id) THEN
    RAISE EXCEPTION 'Task unavailable';
  END IF;

  v_context_team_id := public.resolve_task_context(p_task_id, p_context_team_id);
  IF NOT public.is_full_access()
     AND NOT public.has_related_context_access(p_task_id, v_context_team_id) THEN
    RAISE EXCEPTION 'Task context unavailable';
  END IF;
  PERFORM public.validate_comment_mentions(
    p_task_id, v_context_team_id, p_mentioned_profile_ids
  );
  v_grants_access := public.is_full_access();

  INSERT INTO public.task_comments(task_id, user_id, content, context_team_id)
  VALUES (p_task_id, v_profile_id, btrim(p_content), v_context_team_id)
  RETURNING id INTO v_comment_id;

  INSERT INTO public.task_comment_mentions(
    comment_id, task_id, profile_id, context_team_id, grants_access
  )
  SELECT v_comment_id, p_task_id, mentioned.profile_id, v_context_team_id, v_grants_access
  FROM (
    SELECT DISTINCT unnest(COALESCE(p_mentioned_profile_ids, '{}'::uuid[])) AS profile_id
  ) mentioned;

  PERFORM public.rebuild_task_access_grants(p_task_id);
  RETURN v_comment_id;
END;
$$;

CREATE OR REPLACE FUNCTION public.update_task_comment_with_mentions(
  p_comment_id uuid,
  p_content text,
  p_context_team_id uuid DEFAULT NULL,
  p_mentioned_profile_ids uuid[] DEFAULT '{}'::uuid[]
)
RETURNS uuid
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
DECLARE
  v_comment public.task_comments%ROWTYPE;
  v_profile_id uuid;
  v_context_team_id uuid;
  v_grants_access boolean;
  v_previously_granting_profile_ids uuid[] := '{}'::uuid[];
BEGIN
  SELECT * INTO v_comment
  FROM public.task_comments
  WHERE id = p_comment_id;
  IF NOT FOUND THEN
    RAISE EXCEPTION 'Comment not found';
  END IF;

  v_profile_id := public.current_profile_id();
  IF v_comment.user_id <> v_profile_id
     AND NOT (public.is_full_access() AND public.is_editor()) THEN
    RAISE EXCEPTION 'Only the comment author or an editor can edit this comment';
  END IF;
  IF btrim(COALESCE(p_content, '')) = '' THEN
    RAISE EXCEPTION 'Comment cannot be empty';
  END IF;
  IF NOT public.is_full_access() AND NOT public.has_related_task_access(v_comment.task_id) THEN
    RAISE EXCEPTION 'Task unavailable';
  END IF;

  v_context_team_id := public.resolve_task_context(
    v_comment.task_id, COALESCE(p_context_team_id, v_comment.context_team_id)
  );
  IF NOT public.is_full_access()
     AND NOT public.has_related_context_access(v_comment.task_id, v_context_team_id) THEN
    RAISE EXCEPTION 'Task context unavailable';
  END IF;
  PERFORM public.validate_comment_mentions(
    v_comment.task_id, v_context_team_id, p_mentioned_profile_ids
  );
  v_grants_access := public.is_full_access();

  -- A downgrade must prevent *new* grants, but editing a comment should not
  -- silently revoke mentions that were legitimately created while its author
  -- had full access. Moving a mention to another context is still a new grant.
  SELECT COALESCE(array_agg(m.profile_id), '{}'::uuid[])
  INTO v_previously_granting_profile_ids
  FROM public.task_comment_mentions m
  WHERE m.comment_id = p_comment_id
    AND m.context_team_id = v_context_team_id
    AND m.grants_access;

  UPDATE public.task_comments
  SET content = btrim(p_content),
      context_team_id = v_context_team_id,
      updated_at = now()
  WHERE id = p_comment_id;

  DELETE FROM public.task_comment_mentions WHERE comment_id = p_comment_id;
  INSERT INTO public.task_comment_mentions(
    comment_id, task_id, profile_id, context_team_id, grants_access
  )
  SELECT p_comment_id, v_comment.task_id, mentioned.profile_id,
         v_context_team_id,
         v_grants_access OR mentioned.profile_id = ANY(v_previously_granting_profile_ids)
  FROM (
    SELECT DISTINCT unnest(COALESCE(p_mentioned_profile_ids, '{}'::uuid[])) AS profile_id
  ) mentioned;

  PERFORM public.rebuild_task_access_grants(v_comment.task_id);
  RETURN p_comment_id;
END;
$$;

