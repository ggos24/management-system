-- -----------------------------------------------------------------------------
-- 4. Derive effective grants from every person-bearing source
-- -----------------------------------------------------------------------------

CREATE OR REPLACE FUNCTION public.compute_task_access_grants(p_task_id uuid)
RETURNS TABLE (
  task_id uuid,
  profile_id uuid,
  context_team_id uuid,
  source_type text,
  source_id uuid
)
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
  WITH task_row AS (
    SELECT t.*
    FROM public.tasks t
    WHERE t.id = p_task_id
      AND t.deleted_at IS NULL
  ), sources AS (
    SELECT t.id AS task_id,
           a.member_id AS profile_id,
           t.team_id AS context_team_id,
           'assignee'::text AS source_type,
           a.member_id AS source_id
    FROM task_row t
    JOIN public.task_assignees a ON a.task_id = t.id

    UNION ALL

    SELECT t.id, ids.profile_id, t.team_id, 'editor'::text, ids.profile_id
    FROM task_row t
    CROSS JOIN LATERAL public.jsonb_profile_ids(t.editor_ids) AS ids(profile_id)

    UNION ALL

    SELECT t.id, ids.profile_id, t.team_id, 'designer'::text, ids.profile_id
    FROM task_row t
    CROSS JOIN LATERAL public.jsonb_profile_ids(t.designer_ids) AS ids(profile_id)

    UNION ALL

    SELECT t.id, ids.profile_id, t.team_id, 'custom_person'::text, cp.id
    FROM task_row t
    JOIN public.custom_properties cp
      ON cp.team_id = t.team_id
     AND cp.type = 'person'
    CROSS JOIN LATERAL public.jsonb_profile_ids(t.custom_field_values -> cp.id::text) AS ids(profile_id)

    UNION ALL

    SELECT t.id, ids.profile_id, link.team_id, 'custom_person'::text, cp.id
    FROM task_row t
    JOIN public.task_team_links link ON link.task_id = t.id
    JOIN public.custom_properties cp
      ON cp.team_id = link.team_id
     AND cp.type = 'person'
    CROSS JOIN LATERAL public.jsonb_profile_ids(link.custom_field_values -> cp.id::text) AS ids(profile_id)

    UNION ALL

    SELECT t.id, m.profile_id, m.context_team_id, 'comment_mention'::text, m.comment_id
    FROM task_row t
    JOIN public.task_comment_mentions m ON m.task_id = t.id
    WHERE m.grants_access
      AND (
        m.context_team_id = t.team_id
        OR EXISTS (
          SELECT 1
          FROM public.task_team_links link
          WHERE link.task_id = t.id
            AND link.team_id = m.context_team_id
        )
      )
  )
  SELECT DISTINCT s.task_id, s.profile_id, s.context_team_id, s.source_type, s.source_id
  FROM sources s
  JOIN public.profiles p ON p.id = s.profile_id
$$;

CREATE OR REPLACE FUNCTION public.bump_task_access_revision(p_profile_id uuid)
RETURNS void
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
BEGIN
  INSERT INTO public.task_access_revisions(profile_id, revision, updated_at)
  VALUES (p_profile_id, 1, now())
  ON CONFLICT (profile_id) DO UPDATE
  SET revision = public.task_access_revisions.revision + 1,
      updated_at = now();
END;
$$;

CREATE OR REPLACE FUNCTION public.rebuild_task_access_grants(p_task_id uuid)
RETURNS void
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
BEGIN
  INSERT INTO public.task_access_grants(
    task_id, profile_id, context_team_id, source_type, source_id
  )
  SELECT g.task_id, g.profile_id, g.context_team_id, g.source_type, g.source_id
  FROM public.compute_task_access_grants(p_task_id) g
  ON CONFLICT DO NOTHING;

  DELETE FROM public.task_access_grants existing
  WHERE existing.task_id = p_task_id
    AND NOT EXISTS (
      SELECT 1
      FROM public.compute_task_access_grants(p_task_id) desired
      WHERE desired.task_id = existing.task_id
        AND desired.profile_id = existing.profile_id
        AND desired.context_team_id = existing.context_team_id
        AND desired.source_type = existing.source_type
        AND desired.source_id = existing.source_id
    );
END;
$$;

CREATE OR REPLACE FUNCTION public.notify_task_access_grant_change()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
BEGIN
  IF TG_OP = 'DELETE' THEN
    IF EXISTS (
      SELECT 1 FROM public.profiles p
      WHERE p.id = OLD.profile_id AND p.access_scope = 'related_only'
    ) THEN
      PERFORM public.bump_task_access_revision(OLD.profile_id);
    END IF;
    RETURN OLD;
  END IF;

  IF EXISTS (
    SELECT 1 FROM public.profiles p
    WHERE p.id = NEW.profile_id AND p.access_scope = 'related_only'
  ) THEN
    PERFORM public.bump_task_access_revision(NEW.profile_id);
  END IF;

  IF TG_OP = 'UPDATE' AND OLD.profile_id <> NEW.profile_id AND EXISTS (
    SELECT 1 FROM public.profiles p
    WHERE p.id = OLD.profile_id AND p.access_scope = 'related_only'
  ) THEN
    PERFORM public.bump_task_access_revision(OLD.profile_id);
  END IF;
  RETURN NEW;
END;
$$;

CREATE TRIGGER trg_task_access_grant_revision
AFTER INSERT OR UPDATE OR DELETE ON public.task_access_grants
FOR EACH ROW EXECUTE FUNCTION public.notify_task_access_grant_change();

-- -----------------------------------------------------------------------------
-- 5. Backfill structured legacy mentions, with an audit trail for skipped tokens
-- -----------------------------------------------------------------------------

CREATE OR REPLACE FUNCTION public.legacy_comment_mention_starts(p_content text)
RETURNS SETOF integer
LANGUAGE sql
IMMUTABLE
SET search_path = public, pg_temp
AS $$
  SELECT position
  FROM generate_series(1, char_length(COALESCE(p_content, ''))) positions(position)
  WHERE substring(COALESCE(p_content, '') FROM position FOR 1) = '@'
    AND (
      position = 1
      OR substring(p_content FROM position - 1 FOR 1) ~ '[[:space:]]'
      OR substring(p_content FROM position - 1 FOR 1) = ANY(ARRAY['(', '[', '{'])
    )
$$;

-- Compare a known profile name literally at an @ position, which avoids
-- regex-name escaping bugs and exactly mirrors the client's post-token boundary.
CREATE OR REPLACE FUNCTION public.legacy_profile_mention_at(
  p_content text,
  p_profile_name text,
  p_token_start integer
)
RETURNS boolean
LANGUAGE sql
IMMUTABLE
SET search_path = public, pg_temp
AS $$
  WITH input AS (
    SELECT COALESCE(p_content, '') AS content,
           '@' || regexp_replace(COALESCE(p_profile_name, ''), '[[:space:]]', '', 'g') AS token
  )
  SELECT char_length(input.token) > 1
    AND p_token_start >= 1
    AND lower(substring(input.content FROM p_token_start FOR char_length(input.token))) = lower(input.token)
    AND (
      p_token_start = 1
      OR substring(input.content FROM p_token_start - 1 FOR 1) ~ '[[:space:]]'
      OR substring(input.content FROM p_token_start - 1 FOR 1) = ANY(ARRAY['(', '[', '{'])
    )
    AND (
      p_token_start + char_length(input.token) > char_length(input.content)
      OR substring(input.content FROM p_token_start + char_length(input.token) FOR 1) ~ '[[:space:]]'
      OR substring(input.content FROM p_token_start + char_length(input.token) FOR 1)
         = ANY(ARRAY['.', ',', '!', '?', ';', ':', ')', ']', '}'])
    )
  FROM input
$$;

CREATE OR REPLACE FUNCTION public.legacy_profile_mention_positions(
  p_content text,
  p_profile_name text
)
RETURNS SETOF integer
LANGUAGE sql
IMMUTABLE
SET search_path = public, pg_temp
AS $$
  SELECT position
  FROM public.legacy_comment_mention_starts(p_content) positions(position)
  WHERE public.legacy_profile_mention_at(p_content, p_profile_name, position)
$$;

WITH candidate_matches AS (
  SELECT DISTINCT c.id AS comment_id,
         c.task_id,
         c.context_team_id,
         c.user_id AS author_id,
         positions.token_start,
         p.id AS profile_id
  FROM public.task_comments c
  CROSS JOIN LATERAL public.legacy_comment_mention_starts(c.content) positions(token_start)
  CROSS JOIN public.profiles p
  WHERE public.legacy_profile_mention_at(c.content, p.name, positions.token_start)
), candidates AS (
  SELECT match.comment_id, match.task_id, match.context_team_id, match.author_id,
         match.token_start,
         array_agg(DISTINCT match.profile_id ORDER BY match.profile_id) AS profile_ids,
         count(DISTINCT match.profile_id) AS candidate_count
  FROM candidate_matches match
  GROUP BY match.comment_id, match.task_id, match.context_team_id,
           match.author_id, match.token_start
)
INSERT INTO public.task_comment_mentions(
  comment_id, task_id, profile_id, context_team_id, grants_access
)
SELECT c.comment_id,
       c.task_id,
       c.profile_ids[1],
       c.context_team_id,
       COALESCE(author.access_scope = 'full', false)
FROM candidates c
JOIN public.profiles author ON author.id = c.author_id
WHERE c.candidate_count = 1
ON CONFLICT DO NOTHING;

WITH candidate_matches AS (
  SELECT DISTINCT c.id AS comment_id,
         positions.token_start,
         p.id AS profile_id
  FROM public.task_comments c
  CROSS JOIN LATERAL public.legacy_comment_mention_starts(c.content) positions(token_start)
  CROSS JOIN public.profiles p
  WHERE public.legacy_profile_mention_at(c.content, p.name, positions.token_start)
), candidates AS (
  SELECT match.comment_id, match.token_start,
         array_agg(DISTINCT match.profile_id ORDER BY match.profile_id) AS profile_ids,
         count(DISTINCT match.profile_id) AS candidate_count
  FROM candidate_matches match
  GROUP BY match.comment_id, match.token_start
)
INSERT INTO public.external_access_migration_report(report_type, entity_id, details)
SELECT 'mention_ambiguous',
       c.comment_id,
       jsonb_build_object(
         'tokenStart', c.token_start,
         'candidateProfileIds', to_jsonb(c.profile_ids)
       )
FROM candidates c
WHERE c.candidate_count > 1;

-- Log syntactic @tokens for which no profile name matched at that exact start.
WITH token_starts AS (
  SELECT c.id AS comment_id,
         position AS token_start,
         substring(c.content FROM position FOR 80) AS token_context
  FROM public.task_comments c
  CROSS JOIN LATERAL public.legacy_comment_mention_starts(c.content) positions(position)
), matched_starts AS (
  SELECT DISTINCT c.id AS comment_id, positions.token_start
  FROM public.task_comments c
  CROSS JOIN LATERAL public.legacy_comment_mention_starts(c.content) positions(token_start)
  CROSS JOIN public.profiles p
  WHERE public.legacy_profile_mention_at(c.content, p.name, positions.token_start)
)
INSERT INTO public.external_access_migration_report(report_type, entity_id, details)
SELECT 'mention_unmatched', token.comment_id,
       jsonb_build_object(
         'tokenStart', token.token_start,
         'tokenContext', token.token_context
       )
FROM token_starts token
LEFT JOIN matched_starts matched
  ON matched.comment_id = token.comment_id
 AND matched.token_start = token.token_start
WHERE matched.comment_id IS NULL;

INSERT INTO public.task_access_grants(
  task_id, profile_id, context_team_id, source_type, source_id
)
SELECT g.task_id, g.profile_id, g.context_team_id, g.source_type, g.source_id
FROM public.tasks t
CROSS JOIN LATERAL public.compute_task_access_grants(t.id) g
ON CONFLICT DO NOTHING;

